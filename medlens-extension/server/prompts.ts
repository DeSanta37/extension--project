export function buildMessages(
  text: string,
  level: AdaptLevel,
  translate: boolean,
): Array<{ role: 'system' | 'user'; content: string }> {
  const parts = [SYSTEM_PROMPT];

  if (translate) {
    parts.push(TRANSLATION_PROMPT);
  }

  parts.push(LEVEL_PROMPTS[level]);

  return [
    { role: 'system', content: parts.join('\n\n') },
    {
      role: 'user',
      content: translate
        ? `Переведи и адаптируй следующий текст:\n\n${text}`
        : `Адаптируй следующий текст:\n\n${text}`,
    },
  ];
}

const BLOCK_MODE_PROMPT = `Текст состоит из отдельных блоков (абзацы, пункты списка, заголовки), разделённых маркером <<<MEDLENS_BLOCK>>>.

Требования к ответу:
- Верни ровно столько же блоков в том же порядке — не пропускай и не объединяй блоки
- Разделяй блоки тем же маркером <<<MEDLENS_BLOCK>>>
- Каждый блок — один абзац или один пункт списка; внутри блока без лишних переносов
- Делай формулировки лаконичнее, но сохраняй факты из каждого блока
- Не используй markdown (** __ # - *)
- Не добавляй пустые строки между блоками
- Не добавляй факты, даты и формулировки, которых нет в соответствующем блоке оригинала
- Сохраняй числа, названия и упоминания из оригинала`;

export function buildBlockMessages(
  joinedBlocks: string,
  blockCount: number,
  level: AdaptLevel,
  translate: boolean,
): Array<{ role: 'system' | 'user'; content: string }> {
  const parts = [SYSTEM_PROMPT, BLOCK_MODE_PROMPT];

  if (translate) {
    parts.push(TRANSLATION_PROMPT);
  }

  parts.push(LEVEL_PROMPTS[level]);

  return [
    { role: 'system', content: parts.join('\n\n') },
    {
      role: 'user',
      content: translate
        ? `Переведи и адаптируй ${blockCount} блоков:\n\n${joinedBlocks}`
        : `Адаптируй ${blockCount} блоков:\n\n${joinedBlocks}`,
    },
  ];
}

